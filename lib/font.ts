export function glyph(ch: string): boolean[][] {
  const s = G[ch.toUpperCase()] ?? G["?"];
  const rows: boolean[][] = [];
  for (let y = 0; y < 5; y++) rows.push([s[y * 3] === "#", s[y * 3 + 1] === "#", s[y * 3 + 2] === "#"]);
  return rows;
}

